import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");
const pkg = JSON.parse(fs.readFileSync(path.join(rootDir, "package.json"), "utf8"));
const prefix = process.env.SPIRE_MODULE_PREFIX || "@spire/module-";
const explicit = String(process.env.SPIRE_MODULE_PACKAGES || "")
  .split(",")
  .map((item) => item.trim())
  .filter(Boolean);

const dependencies = { ...(pkg.dependencies || {}), ...(pkg.optionalDependencies || {}) };
const packages = [...new Set([
  ...Object.keys(dependencies).filter((name) => name.startsWith(prefix)),
  ...explicit,
])].sort();

const imports = packages.map((name, index) => `import module${index} from "${name}/web";`);
const content = [
  "// Generated by scripts/generate-module-registry.js. Do not edit manually.",
  ...imports,
  "",
  `export const installedWebModules = [${packages.map((_, i) => `module${i}`).join(", ")}];`,
  "",
].join("\n");

const outputPath = path.join(rootDir, "web", "src", "generated", "modules.js");
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, content);
console.log(`Generated web registry with ${packages.length} module(s).`);
